        [[nodiscard]] u32 SamplesPerQuadOf(const SceneRendererSettings::SsrSamplesPerQuad density)
        {
            switch (density)
            {
            case SceneRendererSettings::SsrSamplesPerQuad::One:
                return 1;
            case SceneRendererSettings::SsrSamplesPerQuad::Two:
                return 2;
            case SceneRendererSettings::SsrSamplesPerQuad::Four:
                return 4;
            }
            VE_ASSERT(false, "SsrStochasticChain: unmapped SsrSamplesPerQuad");
        }

        [[nodiscard]] uvec2 TileGrid(const uvec2 extent)
        {
            return (extent + uvec2(TileSize - 1)) / TileSize;
        }

        [[nodiscard]] uvec2 LevelExtent(const uvec2 base, const u32 level)
        {
            return glm::max(uvec2(base.x >> level, base.y >> level), uvec2(1));
        }

        // The squared perceptual roughness cutoff the view authors: the GGX α a pixel is glossy below.
        [[nodiscard]] f32 MaxAlphaOf(const SceneView& view)
        {
            const f32 maxRoughness = std::max(view.SsrMaxRoughness, 0.0f);
            return maxRoughness * maxRoughness;
        }

