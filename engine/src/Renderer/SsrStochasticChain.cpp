    Unique<SsrStochasticChain>
    SsrStochasticChain::Create(Context& context, AssetManager& assets,
                               const Ref<PipelineLayout>& hiZReduceLayout,
                               const Ref<PipelineLayout>& hiZTailLayout)
    {
        return Unique<SsrStochasticChain>(
            new SsrStochasticChain(context, assets, hiZReduceLayout, hiZTailLayout));
    }

    SsrStochasticChain::SsrStochasticChain(Context& context, AssetManager& assets,
                                           const Ref<PipelineLayout>& hiZReduceLayout,
                                           const Ref<PipelineLayout>& hiZTailLayout)
        : m_Context(context), m_Assets(assets)
    {
        const auto LoadShader = [&](const AssetId id, const char* what) -> AssetHandle<Veng::Shader>
        {
            const AssetResult<AssetHandle<Veng::Shader>> result = assets.LoadSync<Veng::Shader>(id);
            VE_ASSERT(result.has_value(), "SsrStochasticChain: {} shader load failed: {}", what,
                      result.error().Detail);
            return *result;
        };
        const AssetHandle<Veng::Shader> classifyCs = LoadShader(SsrClassifyCompId, "classify");
        const AssetHandle<Veng::Shader> prepareCs =
            LoadShader(SsrPrepareArgsCompId, "prepare arguments");
        const AssetHandle<Veng::Shader> intersectCs = LoadShader(SsrIntersectCompId, "intersect");
        const AssetHandle<Veng::Shader> reduceCs = LoadShader(SsrHiZReduceCompId, "pyramid reduce");
        const AssetHandle<Veng::Shader> tailCs =
            LoadShader(SsrHiZReduceTailCompId, "pyramid reduce tail");

        const auto ComputeBinding = [](const u32 binding, const DescriptorType type)
        {
            return DescriptorBinding{
                .Binding = binding, .Type = type, .Count = 1, .Stages = ShaderStage::Compute};
        };

        m_ClassifySetLayout = DescriptorSetLayout::Create(
            m_Context,
            {
                .Name = "SceneRenderer SSR Classify Set Layout",
                .Bindings =
                    {
                        ComputeBinding(ClassifyRayListBinding, DescriptorType::StorageBuffer),
                        ComputeBinding(ClassifyTileListBinding, DescriptorType::StorageBuffer),
                        ComputeBinding(ClassifyCountersBinding, DescriptorType::StorageBuffer),
                        ComputeBinding(ClassifyRadianceBinding, DescriptorType::StorageImage),
                        ComputeBinding(ClassifyAlphaBinding, DescriptorType::StorageImage),
                        ComputeBinding(ClassifyRayLengthBinding, DescriptorType::StorageImage),
                        ComputeBinding(ClassifyAverageBinding, DescriptorType::StorageImage),
                    },
            });
        m_ClassifyLayout = PipelineLayout::Create(
            m_Context, {
                           .Name = "SceneRenderer SSR Classify Layout",
                           .DescriptorSetLayouts = {m_ClassifySetLayout},
                           .PushConstantRanges = {PushConstantRange::Of<SsrClassifyPush>(
                               ShaderStage::Compute)},
                       });
        m_ClassifyPipeline = ComputePipeline::Create(
            m_Context,
            {
                .Name = "SceneRenderer SSR Classify Pipeline",
                .PipelineLayout = m_ClassifyLayout,
                .ShaderStage = {.Stage = ShaderStage::Compute, .Module = classifyCs.Get()->Module},
            });

        m_PrepareSetLayout = DescriptorSetLayout::Create(
            m_Context,
            {
                .Name = "SceneRenderer SSR Prepare Arguments Set Layout",
                .Bindings =
                    {
                        ComputeBinding(PrepareCountersBinding, DescriptorType::StorageBuffer),
                        ComputeBinding(PrepareArgumentsBinding, DescriptorType::StorageBuffer),
                    },
            });
        m_PrepareLayout =
            PipelineLayout::Create(m_Context, {
                                                  .Name = "SceneRenderer SSR Prepare Layout",
                                                  .DescriptorSetLayouts = {m_PrepareSetLayout},
                                              });
        m_PreparePipeline = ComputePipeline::Create(
            m_Context,
            {
                .Name = "SceneRenderer SSR Prepare Arguments Pipeline",
                .PipelineLayout = m_PrepareLayout,
                .ShaderStage = {.Stage = ShaderStage::Compute, .Module = prepareCs.Get()->Module},
            });

        m_IntersectSetLayout = DescriptorSetLayout::Create(
            m_Context,
            {
                .Name = "SceneRenderer SSR Intersect Set Layout",
                .Bindings =
                    {
                        ComputeBinding(IntersectRayListBinding, DescriptorType::StorageBuffer),
                        ComputeBinding(IntersectCountersBinding, DescriptorType::StorageBuffer),
                        ComputeBinding(IntersectRadianceBinding, DescriptorType::StorageImage),
                        ComputeBinding(IntersectRayLengthBinding, DescriptorType::StorageImage),
                    },
            });
        m_IntersectLayout = PipelineLayout::Create(
            m_Context, {
                           .Name = "SceneRenderer SSR Intersect Layout",
                           .DescriptorSetLayouts = {m_IntersectSetLayout},
                           .PushConstantRanges = {PushConstantRange::Of<SsrIntersectPush>(
                               ShaderStage::Compute)},
                       });
        m_IntersectPipeline = ComputePipeline::Create(
            m_Context,
            {
                .Name = "SceneRenderer SSR Intersect Pipeline",
                .PipelineLayout = m_IntersectLayout,
                .ShaderStage = {.Stage = ShaderStage::Compute, .Module = intersectCs.Get()->Module},
            });

        m_PyramidReducePipeline = ComputePipeline::Create(
            m_Context,
            {
                .Name = "SceneRenderer SSR Stochastic Pyramid Reduce Pipeline",
                .PipelineLayout = hiZReduceLayout,
                .ShaderStage = {.Stage = ShaderStage::Compute, .Module = reduceCs.Get()->Module},
            });
        m_PyramidTailPipeline = ComputePipeline::Create(
            m_Context,
            {
                .Name = "SceneRenderer SSR Stochastic Pyramid Tail Pipeline",
                .PipelineLayout = hiZTailLayout,
                .ShaderStage = {.Stage = ShaderStage::Compute, .Module = tailCs.Get()->Module},
            });

        const auto BuildPass = [&](DenoisePass& pass, const AssetId shaderId, const char* name,
                                   const vector<DescriptorBinding>& bindings,
                                   const PushConstantRange& push)
        {
            const AssetHandle<Veng::Shader> shader = LoadShader(shaderId, name);
            pass.SetLayout = DescriptorSetLayout::Create(
                m_Context, {.Name = fmt::format("SceneRenderer SSR {} Set Layout", name),
                            .Bindings = bindings});
            pass.Layout = PipelineLayout::Create(
                m_Context, {
                               .Name = fmt::format("SceneRenderer SSR {} Layout", name),
                               .DescriptorSetLayouts = {pass.SetLayout},
                               .PushConstantRanges = {push},
                           });
            pass.Pipeline = ComputePipeline::Create(
                m_Context,
                {
                    .Name = fmt::format("SceneRenderer SSR {} Pipeline", name),
                    .PipelineLayout = pass.Layout,
                    .ShaderStage = {.Stage = ShaderStage::Compute, .Module = shader.Get()->Module},
                });
        };
        const DescriptorBinding tileList =
            ComputeBinding(DenoiseTileListBinding, DescriptorType::StorageBuffer);
        BuildPass(m_Reproject, SsrReprojectCompId, "Reproject",
                  {
                      tileList,
                      ComputeBinding(ReprojectReprojectedBinding, DescriptorType::StorageImage),
                      ComputeBinding(ReprojectVarianceBinding, DescriptorType::StorageImage),
                      ComputeBinding(ReprojectSampleCountBinding, DescriptorType::StorageImage),
                      ComputeBinding(ReprojectAverageBinding, DescriptorType::StorageImage),
                  },
                  PushConstantRange::Of<SsrReprojectPush>(ShaderStage::Compute));
        BuildPass(m_Prefilter, SsrPrefilterCompId, "Prefilter",
                  {
                      tileList,
                      ComputeBinding(PrefilterRadianceBinding, DescriptorType::StorageImage),
                      ComputeBinding(PrefilterVarianceBinding, DescriptorType::StorageImage),
                  },
                  PushConstantRange::Of<SsrPrefilterPush>(ShaderStage::Compute));
        BuildPass(m_Resolve, SsrResolveCompId, "Resolve",
                  {
                      tileList,
                      ComputeBinding(ResolveOutputBinding, DescriptorType::StorageImage),
                      ComputeBinding(ResolveVarianceBinding, DescriptorType::StorageImage),
                  },
                  PushConstantRange::Of<SsrResolvePush>(ShaderStage::Compute));
        BuildPass(m_History, SsrDenoiseHistoryCompId, "Denoise History",
                  {
                      ComputeBinding(HistoryNormalBinding, DescriptorType::StorageImage),
                      ComputeBinding(HistoryAlphaBinding, DescriptorType::StorageImage),
                      ComputeBinding(HistoryDepthBinding, DescriptorType::StorageImage),
                      ComputeBinding(HistorySampleCountBinding, DescriptorType::StorageImage),
                      ComputeBinding(HistoryOutputBinding, DescriptorType::StorageImage),
                      ComputeBinding(HistoryVarianceBinding, DescriptorType::StorageImage),
                  },
                  PushConstantRange::Of<SsrDenoiseHistoryPush>(ShaderStage::Compute));

        // Bilinear and clamped, so a history read at a reprojected UV near the edge reads the edge.
        m_HistorySampler = m_Context.GetBindlessRegistry()
                               .AcquireSampler({
                                   .Name = "SceneRenderer SSR History Sampler",
                                   .MagFilter = Filter::Linear,
                                   .MinFilter = Filter::Linear,
                                   .MipmapMode = MipmapMode::Nearest,
                                   .AddressModeU = AddressMode::ClampToEdge,
                                   .AddressModeV = AddressMode::ClampToEdge,
                                   .AddressModeW = AddressMode::ClampToEdge,
                                   .AnisotropyEnabled = false,
                                   .MaxLod = 0.0f,
                               })
                               .Handle;
    }

    SsrStochasticChain::~SsrStochasticChain()
    {
        BindlessRegistry& bindless = m_Context.GetBindlessRegistry();
        bindless.Release(m_RadianceHandle);
        bindless.Release(m_AlphaHandle);
        bindless.Release(m_BlueNoiseHandle);
        bindless.Release(m_PyramidHandle);
        bindless.Release(m_RayLengthHandle);
        for (const DenoiseTarget& target : m_DenoiseTargets)
        {
            bindless.Release(target.Handle);
        }
    }

    void SsrStochasticChain::EnsureBlueNoise()
    {
        if (m_BlueNoiseImage != nullptr)
        {
            return;
        }
        const AssetResult<AssetHandle<RawAsset>> noise =
            m_Assets.LoadSync<RawAsset>(SsrBlueNoiseId);
        VE_ASSERT(noise.has_value(), "SsrStochasticChain: failed to load the blue-noise tile");
        const vector<u8>& bytes = noise.value().Get()->Bytes;
        constexpr usize TileBytes = static_cast<usize>(BlueNoiseSize) * BlueNoiseSize * 2;
        VE_ASSERT(bytes.size() == TileBytes,
                  "SsrStochasticChain: the blue-noise tile is {} bytes, expected {}", bytes.size(),
                  TileBytes);

        m_BlueNoiseImage =
            Image::Create(m_Context, {
                                         .Name = "SceneRenderer SSR Blue Noise",
                                         .Extent = {BlueNoiseSize, BlueNoiseSize, 1},
                                         .Format = Format::RG8Unorm,
                                         .Usage = ImageUsage::Sampled | ImageUsage::TransferDst,
                                     });
        m_BlueNoiseView = ImageView::Create(
            m_Context, {.Name = "SceneRenderer SSR Blue Noise View", .Image = m_BlueNoiseImage});
        const Ref<Buffer> staging =
            Buffer::Create(m_Context, {
                                          .Name = "SceneRenderer SSR Blue Noise (Upload)",
                                          .Size = bytes.size(),
                                          .Usage = BufferUsage::TransferSrc,
                                      });
        staging->UploadSync(bytes);
        // Recorded as setup work, so a renderer built mid-frame waits behind no frame in flight.
        m_Context.RecordSetupCommands(
            [view = m_BlueNoiseView, staging](CommandBuffer& cmd)
            {
                cmd.PrepareForAccess(view, AccessKind::TransferDst);
                cmd.CopyBufferToImage(staging, view->GetImage());
                cmd.PrepareForAccess(view, AccessKind::SampleAny);
            });
        m_BlueNoiseHandle = m_Context.GetBindlessRegistry().Register(m_BlueNoiseView);
    }

    void SsrStochasticChain::CreatePyramid(const Ref<ImageView>& depthView,
                                           const Ref<DescriptorSetLayout>& hiZReduceSetLayout,
                                           const Ref<DescriptorSetLayout>& hiZTailSetLayout)
    {
        const u32 levels = std::min(
            PyramidMaxLevels, static_cast<u32>(std::bit_width(std::max(m_Extent.x, m_Extent.y))));
        m_PyramidImage =
            Image::Create(m_Context, {
                                         .Name = "SceneRenderer SSR Stochastic Pyramid",
                                         .Extent = {m_Extent.x, m_Extent.y, 1},
                                         .MipLevels = levels,
                                         .Format = PyramidFormat,
                                         .Usage = ImageUsage::Storage | ImageUsage::Sampled |
                                                  ImageUsage::TransferSrc,
                                     });
        m_PyramidMips.clear();
        m_PyramidMips.reserve(levels);
        for (u32 level = 0; level < levels; level++)
        {
            m_PyramidMips.push_back(ImageView::Create(
                m_Context,
                {
                    .Name = fmt::format("SceneRenderer SSR Stochastic Pyramid Mip {} View", level),
                    .Image = m_PyramidImage,
                    .BaseMipLevel = level,
                    .MipLevels = 1,
                }));
        }
        m_PyramidSampleView =
            ImageView::Create(m_Context, {
                                             .Name = "SceneRenderer SSR Stochastic Pyramid View",
                                             .Image = m_PyramidImage,
                                             .MipLevels = levels,
                                         });
        m_PyramidHandle = m_Context.GetBindlessRegistry().Register(m_PyramidSampleView);

        // Set k binds level k's source — the depth target for level 0, which copies it, and
        // level k-1 otherwise — and level k's destination.
        m_PyramidReduceSets.clear();
        m_PyramidReduceSets.reserve(levels);
        for (u32 level = 0; level < levels; level++)
        {
            Ref<DescriptorSet> set = DescriptorSet::Create(
                m_Context, {
                               .Name = fmt::format(
                                   "SceneRenderer SSR Stochastic Pyramid Reduce Set {}", level),
                               .Layout = hiZReduceSetLayout,
                           });
            set->Write(0, level == 0 ? depthView : m_PyramidMips[level - 1]);
            set->Write(1, m_PyramidMips[level]);
            m_PyramidReduceSets.push_back(std::move(set));
        }

        // Level 0 copies the depth target, a different footprint, so the tail starts no earlier
        // than level 1. The slots past its length repeat its last level, bound but never written.
        m_PyramidTailFirst = MipTailFirstLevel(m_Extent, levels, 1, PyramidTailTexelCapacity);
        m_PyramidTailSet.reset();
        if (m_PyramidTailFirst < levels)
        {
            m_PyramidTailSet = DescriptorSet::Create(
                m_Context, {.Name = "SceneRenderer SSR Stochastic Pyramid Tail Set",
                            .Layout = hiZTailSetLayout});
            m_PyramidTailSet->Write(0, m_PyramidMips[m_PyramidTailFirst - 1]);
            for (u32 slot = 0; slot < MipTailMaxLevels; slot++)
            {
                m_PyramidTailSet->Write(
                    PyramidTailFirstStorageBinding + slot,
                    m_PyramidMips[std::min(m_PyramidTailFirst + slot, levels - 1)]);
            }
        }
    }

    void SsrStochasticChain::Recreate(const SceneRendererSettings& settings, const uvec2 extent,
                                      const Ref<ImageView>& depthView,
                                      const Ref<DescriptorSetLayout>& hiZReduceSetLayout,
                                      const Ref<DescriptorSetLayout>& hiZTailSetLayout)
    {
        m_Extent = glm::max(extent, uvec2(1));
        m_SamplesPerQuad = SamplesPerQuadOf(settings.SsrDensity);

        BindlessRegistry& bindless = m_Context.GetBindlessRegistry();
        bindless.Release(m_RadianceHandle);
        bindless.Release(m_AlphaHandle);
        bindless.Release(m_PyramidHandle);
        bindless.Release(m_RayLengthHandle);
        m_RadianceHandle = {};
        m_AlphaHandle = {};
        m_PyramidHandle = {};
        m_RayLengthHandle = {};
        for (DenoiseTarget& target : m_DenoiseTargets)
        {
            bindless.Release(target.Handle);
            target = {};
        }
        for (DenoisePass* pass : {&m_Reproject, &m_Prefilter, &m_Resolve, &m_History})
        {
            pass->Set.reset();
        }
        m_HistoryValid = false;
        m_RadianceImage.reset();
        m_RadianceView.reset();
        m_AlphaImage.reset();
        m_AlphaView.reset();
        m_RayLengthImage.reset();
        m_RayLengthView.reset();
        m_PyramidImage.reset();
        m_PyramidMips.clear();
        m_PyramidSampleView.reset();
        m_PyramidReduceSets.clear();
        m_PyramidTailSet.reset();
        m_RayList.reset();
        m_TileList.reset();
        m_Counters.reset();
        m_Arguments.reset();
        m_ClassifySet.reset();
        m_PrepareSet.reset();
        m_IntersectSet.reset();
        m_RayListId = {};
        m_TileListId = {};
        m_CountersId = {};
        m_ArgumentsId = {};
        m_RadianceId = {};
        m_AlphaId = {};
        m_RayLengthId = {};
        m_PyramidChainId = {};

        const bool ssrRuns = settings.SSR || settings.Mode == DebugView::Reflections;
        if (!ssrRuns || settings.SsrMethod != SceneRendererSettings::SsrTechnique::Stochastic)
        {
            return;
        }
        VE_ASSERT(m_Extent.x <= RayMaxX + 1 && m_Extent.y <= RayMaxY + 1,
                  "SsrStochasticChain: a {}x{} render exceeds the ray list's {}x{} pixel range",
                  m_Extent.x, m_Extent.y, RayMaxX + 1, RayMaxY + 1);
        EnsureBlueNoise();

        const auto CreateTarget = [&](const char* name, const Format format, Ref<Image>& image,
                                      Ref<ImageView>& view) -> TextureHandle
        {
            image = Image::Create(m_Context, {
                                                 .Name = name,
                                                 .Extent = {m_Extent.x, m_Extent.y, 1},
                                                 .Format = format,
                                                 .Usage = TargetUsage,
                                             });
            view = ImageView::Create(m_Context, {.Name = string(name) + " View", .Image = image});
            return bindless.Register(view);
        };
        m_RadianceHandle = CreateTarget("SceneRenderer SSR Stochastic Radiance", RadianceFormat,
                                        m_RadianceImage, m_RadianceView);
        m_AlphaHandle = CreateTarget("SceneRenderer SSR Stochastic Alpha", AlphaFormat,
                                     m_AlphaImage, m_AlphaView);
        m_RayLengthImage = Image::Create(m_Context, {
                                                        .Name = "SceneRenderer SSR Ray Length",
                                                        .Extent = {m_Extent.x, m_Extent.y, 1},
                                                        .Format = RayLengthFormat,
                                                        .Usage = TargetUsage,
                                                    });
        m_RayLengthView = ImageView::Create(
            m_Context, {.Name = "SceneRenderer SSR Ray Length View", .Image = m_RayLengthImage});
        m_RayLengthHandle = bindless.Register(m_RayLengthView);
        CreatePyramid(depthView, hiZReduceSetLayout, hiZTailSetLayout);

        const uvec2 tiles = TileGrid(m_Extent);
        const u64 pixels = static_cast<u64>(m_Extent.x) * m_Extent.y;
        const u64 tileCount = static_cast<u64>(tiles.x) * tiles.y;
        m_RayList = Buffer::Create(m_Context, {
                                                  .Name = "SceneRenderer SSR Ray List",
                                                  .Size = pixels * sizeof(u32),
                                                  .Usage = BufferUsage::Storage,
                                                  .DeviceLocal = true,
                                              });
        m_TileList = Buffer::Create(m_Context, {
                                                   .Name = "SceneRenderer SSR Tile List",
                                                   .Size = tileCount * sizeof(u32),
                                                   .Usage = BufferUsage::Storage,
                                                   .DeviceLocal = true,
                                               });
        m_Arguments =
            Buffer::Create(m_Context, {
                                          .Name = "SceneRenderer SSR Dispatch Arguments",
                                          .Size = ArgumentWords * sizeof(u32),
                                          .Usage = BufferUsage::Storage | BufferUsage::Indirect,
                                          .DeviceLocal = true,
                                      });
        // The classifier appends to the counters from the first frame, so they start at zero; a
        // host-visible buffer takes that with a plain write, no GPU command.
        m_Counters = Buffer::Create(m_Context, {
                                                   .Name = "SceneRenderer SSR Counters",
                                                   .Size = CounterCount * sizeof(u32),
                                                   .Usage = BufferUsage::Storage,
                                               });
        constexpr std::array<u32, CounterCount> ZeroCounters{};
        m_Counters->UploadSync(
            std::span(reinterpret_cast<const u8*>(ZeroCounters.data()), sizeof(ZeroCounters)));

        m_ClassifySet = DescriptorSet::Create(
            m_Context, {.Name = "SceneRenderer SSR Classify Set", .Layout = m_ClassifySetLayout});
        m_ClassifySet->Write(ClassifyRayListBinding, m_RayList);
        m_ClassifySet->Write(ClassifyTileListBinding, m_TileList);
        m_ClassifySet->Write(ClassifyCountersBinding, m_Counters);
        m_ClassifySet->Write(ClassifyRadianceBinding, m_RadianceView);
        m_ClassifySet->Write(ClassifyAlphaBinding, m_AlphaView);
        m_ClassifySet->Write(ClassifyRayLengthBinding, m_RayLengthView);

        m_PrepareSet = DescriptorSet::Create(
            m_Context, {.Name = "SceneRenderer SSR Prepare Set", .Layout = m_PrepareSetLayout});
        m_PrepareSet->Write(PrepareCountersBinding, m_Counters);
        m_PrepareSet->Write(PrepareArgumentsBinding, m_Arguments);

        m_IntersectSet = DescriptorSet::Create(
            m_Context, {.Name = "SceneRenderer SSR Intersect Set", .Layout = m_IntersectSetLayout});
        m_IntersectSet->Write(IntersectRayListBinding, m_RayList);
        m_IntersectSet->Write(IntersectCountersBinding, m_Counters);
        m_IntersectSet->Write(IntersectRadianceBinding, m_RadianceView);
        m_IntersectSet->Write(IntersectRayLengthBinding, m_RayLengthView);

        CreateDenoiser();
        m_ClassifySet->Write(ClassifyAverageBinding, Target(DenoiseSlot::Average).View);
    }

    void SsrStochasticChain::CreateDenoiser()
    {
        static_assert(DenoiseTargetSpecs.size() == static_cast<usize>(DenoiseSlot::Count));
        BindlessRegistry& bindless = m_Context.GetBindlessRegistry();
        const uvec2 tiles = TileGrid(m_Extent);
        for (usize slot = 0; slot < m_DenoiseTargets.size(); ++slot)
        {
            const DenoiseTargetSpec& spec = DenoiseTargetSpecs[slot];
            const uvec2 extent = spec.PerTile ? tiles : m_Extent;
            DenoiseTarget& target = m_DenoiseTargets[slot];
            target.Image = Image::Create(m_Context, {
                                                        .Name = spec.Name,
                                                        .Extent = {extent.x, extent.y, 1},
                                                        .Format = spec.Format,
                                                        .Usage = TargetUsage,
                                                    });
            target.View = ImageView::Create(
                m_Context, {.Name = string(spec.Name) + " View", .Image = target.Image});
            target.Handle = bindless.Register(target.View);
        }

        const auto CreateSet = [&](DenoisePass& pass, const char* name)
        {
            pass.Set = DescriptorSet::Create(
                m_Context,
                {.Name = fmt::format("SceneRenderer SSR {} Set", name), .Layout = pass.SetLayout});
        };
        CreateSet(m_Reproject, "Reproject");
        m_Reproject.Set->Write(DenoiseTileListBinding, m_TileList);
        m_Reproject.Set->Write(ReprojectReprojectedBinding, Target(DenoiseSlot::Reprojected).View);
        m_Reproject.Set->Write(ReprojectVarianceBinding,
                               Target(DenoiseSlot::ReprojectedVariance).View);
        m_Reproject.Set->Write(ReprojectSampleCountBinding, Target(DenoiseSlot::SampleCount).View);
        m_Reproject.Set->Write(ReprojectAverageBinding, Target(DenoiseSlot::Average).View);

        CreateSet(m_Prefilter, "Prefilter");
        m_Prefilter.Set->Write(DenoiseTileListBinding, m_TileList);
        m_Prefilter.Set->Write(PrefilterRadianceBinding, Target(DenoiseSlot::Prefiltered).View);
        m_Prefilter.Set->Write(PrefilterVarianceBinding, Target(DenoiseSlot::Variance).View);

        CreateSet(m_Resolve, "Resolve");
        m_Resolve.Set->Write(DenoiseTileListBinding, m_TileList);
        m_Resolve.Set->Write(ResolveOutputBinding, Target(DenoiseSlot::Output).View);
        m_Resolve.Set->Write(ResolveVarianceBinding, Target(DenoiseSlot::Variance).View);

        CreateSet(m_History, "Denoise History");
        m_History.Set->Write(HistoryNormalBinding, Target(DenoiseSlot::NormalHistory).View);
        m_History.Set->Write(HistoryAlphaBinding, Target(DenoiseSlot::AlphaHistory).View);
        m_History.Set->Write(HistoryDepthBinding, Target(DenoiseSlot::DepthHistory).View);
        m_History.Set->Write(HistorySampleCountBinding,
                             Target(DenoiseSlot::SampleCountHistory).View);
        m_History.Set->Write(HistoryOutputBinding, Target(DenoiseSlot::Output).View);
        m_History.Set->Write(HistoryVarianceBinding, Target(DenoiseSlot::Variance).View);
    }

    void SsrStochasticChain::Import(RenderGraph& graph)
    {
        VE_ASSERT(IsAllocated(), "SsrStochasticChain::Import: the chain is not allocated");
        m_RayListId = graph.ImportBuffer("SceneRenderer SSR Ray List");
        m_TileListId = graph.ImportBuffer("SceneRenderer SSR Tile List");
        m_CountersId = graph.ImportBuffer("SceneRenderer SSR Counters");
        m_ArgumentsId = graph.ImportBuffer("SceneRenderer SSR Dispatch Arguments");
        m_RadianceId = graph.Import("SceneRenderer SSR Stochastic Radiance");
        m_AlphaId = graph.Import("SceneRenderer SSR Stochastic Alpha");
        m_RayLengthId = graph.Import("SceneRenderer SSR Ray Length");
        m_PyramidChainId = graph.ImportImageMips("SceneRenderer SSR Stochastic Pyramid",
                                                 static_cast<u32>(m_PyramidMips.size()));
        for (usize slot = 0; slot < m_DenoiseTargets.size(); ++slot)
        {
            m_DenoiseTargets[slot].Id = graph.Import(DenoiseTargetSpecs[slot].Name);
        }
    }

    void SsrStochasticChain::DeclarePyramid(RenderGraph& graph, const ResourceId depthId)
    {
        const u32 levels = static_cast<u32>(m_PyramidMips.size());
        const u32 tailFirst = m_PyramidTailSet != nullptr ? m_PyramidTailFirst : levels;
        for (u32 level = 0; level < tailFirst; level++)
        {
            RenderGraph::PassBuilder builder =
                graph.AddComputePass(fmt::format("SSR Stochastic Pyramid Mip {}", level));
            builder.Sample(level == 0 ? depthId : m_PyramidChainId.Level(level - 1));
            builder.StorageWrite(m_PyramidChainId.Level(level));
            const PyramidReducePush push{
                .DestExtent = LevelExtent(m_Extent, level),
                .SourceExtent = level == 0 ? m_Extent : LevelExtent(m_Extent, level - 1),
            };
            builder.Execute(
                [pipeline = m_PyramidReducePipeline, set = m_PyramidReduceSets[level],
                 push](PassContext& inner)
                {
                    CommandBuffer& cmd = inner.Cmd();
                    cmd.BindPipeline(pipeline);
                    cmd.BindDescriptorSets(DescriptorSetBindInfo{
                        .Sets = {set},
                        .FirstSet = 3, // sets 0-2 are the typed bindless registries
                        .PipelineBindPoint = PipelineBindPoint::Compute,
                    });
                    cmd.PushConstants(push);
                    cmd.Dispatch((push.DestExtent.x + 7) / 8, (push.DestExtent.y + 7) / 8, 1);
                });
        }
        if (tailFirst < levels)
        {
            RenderGraph::PassBuilder tail = graph.AddComputePass(
                fmt::format("SSR Stochastic Pyramid Tail Mips {}-{}", tailFirst, levels - 1));
            tail.Sample(m_PyramidChainId.Level(tailFirst - 1));
            for (u32 level = tailFirst; level < levels; level++)
            {
                tail.StorageWrite(m_PyramidChainId.Level(level));
            }
            const PyramidTailPush push{
                .Extent = m_Extent,
                .FirstLevel = tailFirst,
                .LevelCount = levels - tailFirst,
            };
            tail.Execute(
                [pipeline = m_PyramidTailPipeline, set = m_PyramidTailSet, push](PassContext& inner)
                {
                    CommandBuffer& cmd = inner.Cmd();
                    cmd.BindPipeline(pipeline);
                    cmd.BindDescriptorSets(DescriptorSetBindInfo{
                        .Sets = {set},
                        .FirstSet = 3,
                        .PipelineBindPoint = PipelineBindPoint::Compute,
                    });
                    cmd.PushConstants(push);
                    cmd.Dispatch(1, 1, 1);
                });
        }
    }

    void SsrStochasticChain::Declare(RenderGraph& graph, const ResourceId depthId,
                                     const ResourceId normalId, const ResourceId ormId,
                                     const ResourceId velocityId, const ResourceId sceneId,
                                     const TextureHandle depthHandle,
                                     const TextureHandle normalHandle,
                                     const TextureHandle ormHandle,
                                     const TextureHandle velocityHandle,
                                     const TextureHandle sceneHandle)
    {
        VE_ASSERT(m_RadianceId.IsValid(), "SsrStochasticChain::Declare: Import has not run");

        DeclarePyramid(graph, depthId);

        // Classify: the counters are read and written by the appends, so the pass declares both
        // and the graph orders its atomics after the previous frame's argument pass. It reads the
        // variance the last committed frame resolved, and zeroes the averages of the tiles it does
        // not list.
        {
            const uvec2 tiles = TileGrid(m_Extent);
            const Ref<ComputePipeline> pipeline = m_ClassifyPipeline;
            const Ref<DescriptorSet> set = m_ClassifySet;
            const SsrClassifyPush push{
                .DepthTexture = depthHandle.Index,
                .NormalTexture = normalHandle.Index,
                .OrmTexture = ormHandle.Index,
                .VarianceTexture = NoVariance,
                .ViewConstantsIndex = 0,
                .SamplesPerQuad = m_SamplesPerQuad,
                .MaxAlpha = 0.0f,
                .Pad0 = 0,
                .Extent = m_Extent,
            };
            graph.AddComputePass("SSR Classify")
                .Sample(depthId)
                .Sample(normalId)
                .Sample(ormId)
                .Sample(Target(DenoiseSlot::Variance).Id)
                .StorageWrite(Target(DenoiseSlot::Average).Id)
                .StorageBufferWrite(m_RayListId)
                .StorageBufferWrite(m_TileListId)
                .StorageBufferRead(m_CountersId)
                .StorageBufferWrite(m_CountersId)
                .StorageWrite(m_RadianceId)
                .StorageWrite(m_AlphaId)
                .StorageWrite(m_RayLengthId)
                .Execute(
                    [this, pipeline, set, push, tiles](PassContext& inner)
                    {
                        const auto* view = static_cast<const SceneView*>(inner.UserData());
                        VE_ASSERT(view != nullptr, "SSR classify pass: null SceneView");
                        const BindlessRegistry& registry = m_Context.GetBindlessRegistry();
                        CommandBuffer& cmd = inner.Cmd();
                        cmd.BindPipeline(pipeline);
                        registry.Bind(cmd, PipelineBindPoint::Compute);
                        cmd.BindDescriptorSets(DescriptorSetBindInfo{
                            .Sets = {set},
                            .FirstSet = 3, // sets 0-2 are the typed bindless registries
                            .PipelineBindPoint = PipelineBindPoint::Compute,
                        });
                        SsrClassifyPush framePush = push;
                        framePush.ViewConstantsIndex = registry.GetCurrentViewConstantsIndex();
                        framePush.MaxAlpha = MaxAlphaOf(*view);
                        framePush.VarianceTexture = m_HistoryValid
                                                        ? Target(DenoiseSlot::Variance).Handle.Index
                                                        : NoVariance;
                        cmd.PushConstants(framePush);
                        cmd.Dispatch(tiles.x, tiles.y, 1);
                    });
        }

        // Prepare the arguments: the totals become dispatch records, and the counters rotate.
        {
            const Ref<ComputePipeline> pipeline = m_PreparePipeline;
            const Ref<DescriptorSet> set = m_PrepareSet;
            graph.AddComputePass("SSR Prepare Arguments")
                .StorageBufferRead(m_CountersId)
                .StorageBufferWrite(m_CountersId)
                .StorageBufferWrite(m_ArgumentsId)
                .Execute(
                    [pipeline, set](PassContext& inner)
                    {
                        CommandBuffer& cmd = inner.Cmd();
                        cmd.BindPipeline(pipeline);
                        cmd.BindDescriptorSets(DescriptorSetBindInfo{
                            .Sets = {set},
                            .FirstSet = 3,
                            .PipelineBindPoint = PipelineBindPoint::Compute,
                        });
                        cmd.Dispatch(1, 1, 1);
                    });
        }

        // Intersect: one invocation per listed ray, dispatched by the record the argument pass
        // wrote, reading the lit scene as it stands at this declaration.
        {
            RenderGraph::PassBuilder builder = graph.AddComputePass("SSR Intersect");
            builder.IndirectRead(m_ArgumentsId)
                .StorageBufferRead(m_RayListId)
                .StorageBufferRead(m_CountersId)
                .Sample(normalId)
                .Sample(m_AlphaId)
                .Sample(sceneId);
            const u32 levels = static_cast<u32>(m_PyramidMips.size());
            for (u32 level = 0; level < levels; level++)
            {
                builder.Sample(m_PyramidChainId.Level(level));
            }
            builder.StorageWrite(m_RadianceId).StorageWrite(m_RayLengthId);
            const SsrIntersectPush push{
                .PyramidTexture = m_PyramidHandle.Index,
                .NormalTexture = normalHandle.Index,
                .AlphaTexture = m_AlphaHandle.Index,
                .BlueNoiseTexture = m_BlueNoiseHandle.Index,
                .SceneTexture = sceneHandle.Index,
                .ViewConstantsIndex = 0,
                .PyramidLevels = levels,
                .MaxIterations = 1,
                .Extent = m_Extent,
                .Thickness = 0.0f,
                .Pad0 = 0,
            };
            builder.Execute(
                [this, pipeline = m_IntersectPipeline, set = m_IntersectSet,
                 arguments = m_Arguments, push](PassContext& inner)
                {
                    const auto* view = static_cast<const SceneView*>(inner.UserData());
                    VE_ASSERT(view != nullptr, "SSR intersect pass: null SceneView");
                    const BindlessRegistry& registry = m_Context.GetBindlessRegistry();
                    CommandBuffer& cmd = inner.Cmd();
                    cmd.BindPipeline(pipeline);
                    registry.Bind(cmd, PipelineBindPoint::Compute);
                    cmd.BindDescriptorSets(DescriptorSetBindInfo{
                        .Sets = {set},
                        .FirstSet = 3,
                        .PipelineBindPoint = PipelineBindPoint::Compute,
                    });
                    SsrIntersectPush framePush = push;
                    framePush.ViewConstantsIndex = registry.GetCurrentViewConstantsIndex();
                    framePush.MaxIterations = ClampSsrMaxSteps(view->SsrMaxSteps);
                    framePush.Thickness = std::max(view->SsrThickness, 0.0f);
                    cmd.PushConstants(framePush);
                    cmd.DispatchIndirect(arguments, IntersectArgumentsOffset);
                });
        }

        DeclareDenoiser(graph, normalId, velocityId, normalHandle, velocityHandle);
    }

    void SsrStochasticChain::DeclareDenoiser(RenderGraph& graph, const ResourceId normalId,
                                             const ResourceId velocityId,
                                             const TextureHandle normalHandle,
                                             const TextureHandle velocityHandle)
    {
        const ResourceId depthLevel = m_PyramidChainId.Level(0);
        const auto Bind =
            [](CommandBuffer& cmd, const BindlessRegistry& registry, const DenoisePass& pass)
        {
            cmd.BindPipeline(pass.Pipeline);
            registry.Bind(cmd, PipelineBindPoint::Compute);
            cmd.BindDescriptorSets(DescriptorSetBindInfo{
                .Sets = {pass.Set},
                .FirstSet = 3, // sets 0-2 are the typed bindless registries
                .PipelineBindPoint = PipelineBindPoint::Compute,
            });
        };

        // Reproject: last frame's output, variance, sample counts and surface histories, read at
        // where this frame's pixels stood then.
        {
            const SsrReprojectPush push{
                .RadianceTexture = m_RadianceHandle.Index,
                .RayLengthTexture = m_RayLengthHandle.Index,
                .AlphaTexture = m_AlphaHandle.Index,
                .NormalTexture = normalHandle.Index,
                .DepthTexture = m_PyramidHandle.Index,
                .VelocityTexture = velocityHandle.Index,
                .RadianceHistoryTexture = Target(DenoiseSlot::Output).Handle.Index,
                .VarianceHistoryTexture = Target(DenoiseSlot::Variance).Handle.Index,
                .SampleCountHistoryTexture = Target(DenoiseSlot::SampleCountHistory).Handle.Index,
                .NormalHistoryTexture = Target(DenoiseSlot::NormalHistory).Handle.Index,
                .AlphaHistoryTexture = Target(DenoiseSlot::AlphaHistory).Handle.Index,
                .DepthHistoryTexture = Target(DenoiseSlot::DepthHistory).Handle.Index,
                .Sampler = m_HistorySampler.Index,
                .ViewConstantsIndex = 0,
                .Extent = m_Extent,
                .MaxAlpha = 0.0f,
                .HistoryValid = 0,
                .Pad0 = 0,
                .Pad1 = 0,
                .PrevClipTranslation = vec4(0.0f),
            };
            graph.AddComputePass("SSR Reproject")
                .IndirectRead(m_ArgumentsId)
                .StorageBufferRead(m_TileListId)
                .Sample(m_RadianceId)
                .Sample(m_RayLengthId)
                .Sample(m_AlphaId)
                .Sample(normalId)
                .Sample(depthLevel)
                .Sample(velocityId)
                .Sample(Target(DenoiseSlot::Output).Id)
                .Sample(Target(DenoiseSlot::Variance).Id)
                .Sample(Target(DenoiseSlot::SampleCountHistory).Id)
                .Sample(Target(DenoiseSlot::NormalHistory).Id)
                .Sample(Target(DenoiseSlot::AlphaHistory).Id)
                .Sample(Target(DenoiseSlot::DepthHistory).Id)
                .StorageWrite(Target(DenoiseSlot::Reprojected).Id)
                .StorageWrite(Target(DenoiseSlot::ReprojectedVariance).Id)
                .StorageWrite(Target(DenoiseSlot::SampleCount).Id)
                .StorageWrite(Target(DenoiseSlot::Average).Id)
                .Execute(
                    [this, Bind, push](PassContext& inner)
                    {
                        const auto* view = static_cast<const SceneView*>(inner.UserData());
                        VE_ASSERT(view != nullptr, "SSR reproject pass: null SceneView");
                        const BindlessRegistry& registry = m_Context.GetBindlessRegistry();
                        CommandBuffer& cmd = inner.Cmd();
                        Bind(cmd, registry, m_Reproject);
                        SsrReprojectPush framePush = push;
                        framePush.ViewConstantsIndex = registry.GetCurrentViewConstantsIndex();
                        framePush.MaxAlpha = MaxAlphaOf(*view);
                        framePush.HistoryValid = m_HistoryValid ? 1u : 0u;
                        framePush.PrevClipTranslation = m_PrevClipTranslation;
                        cmd.PushConstants(framePush);
                        cmd.DispatchIndirect(m_Arguments, DenoiseArgumentsOffset);
                    });
        }

        // Prefilter: this frame's noisy radiance, spread over the neighbours sharing its surface.
        // It writes the variance target, whose history the reprojection has finished reading.
        {
            const SsrPrefilterPush push{
                .RadianceTexture = m_RadianceHandle.Index,
                .VarianceTexture = Target(DenoiseSlot::ReprojectedVariance).Handle.Index,
                .AlphaTexture = m_AlphaHandle.Index,
                .NormalTexture = normalHandle.Index,
                .DepthTexture = m_PyramidHandle.Index,
                .AverageTexture = Target(DenoiseSlot::Average).Handle.Index,
                .Sampler = m_HistorySampler.Index,
                .ViewConstantsIndex = 0,
                .Extent = m_Extent,
                .MaxAlpha = 0.0f,
                .Pad0 = 0,
            };
            graph.AddComputePass("SSR Prefilter")
                .IndirectRead(m_ArgumentsId)
                .StorageBufferRead(m_TileListId)
                .Sample(m_RadianceId)
                .Sample(Target(DenoiseSlot::ReprojectedVariance).Id)
                .Sample(m_AlphaId)
                .Sample(normalId)
                .Sample(depthLevel)
                .Sample(Target(DenoiseSlot::Average).Id)
                .StorageWrite(Target(DenoiseSlot::Prefiltered).Id)
                .StorageWrite(Target(DenoiseSlot::Variance).Id)
                .Execute(
                    [this, Bind, push](PassContext& inner)
                    {
                        const auto* view = static_cast<const SceneView*>(inner.UserData());
                        VE_ASSERT(view != nullptr, "SSR prefilter pass: null SceneView");
                        const BindlessRegistry& registry = m_Context.GetBindlessRegistry();
                        CommandBuffer& cmd = inner.Cmd();
                        Bind(cmd, registry, m_Prefilter);
                        SsrPrefilterPush framePush = push;
                        framePush.ViewConstantsIndex = registry.GetCurrentViewConstantsIndex();
                        framePush.MaxAlpha = MaxAlphaOf(*view);
                        cmd.PushConstants(framePush);
                        cmd.DispatchIndirect(m_Arguments, DenoiseArgumentsOffset);
                    });
        }

        // Resolve: the filtered radiance blended into its clipped history, into the output; the
        // variance it reads is the filter's, resolved in place.
        {
            const SsrResolvePush push{
                .PrefilteredTexture = Target(DenoiseSlot::Prefiltered).Handle.Index,
                .ReprojectedTexture = Target(DenoiseSlot::Reprojected).Handle.Index,
                .SampleCountTexture = Target(DenoiseSlot::SampleCount).Handle.Index,
                .AverageTexture = Target(DenoiseSlot::Average).Handle.Index,
                .AlphaTexture = m_AlphaHandle.Index,
                .Sampler = m_HistorySampler.Index,
                .Extent = m_Extent,
                .MaxAlpha = 0.0f,
                .Pad0 = 0,
                .Pad1 = 0,
                .Pad2 = 0,
            };
            graph.AddComputePass("SSR Resolve")
                .IndirectRead(m_ArgumentsId)
                .StorageBufferRead(m_TileListId)
                .Sample(Target(DenoiseSlot::Prefiltered).Id)
                .Sample(Target(DenoiseSlot::Reprojected).Id)
                .Sample(Target(DenoiseSlot::SampleCount).Id)
                .Sample(Target(DenoiseSlot::Average).Id)
                .Sample(m_AlphaId)
                .StorageWrite(Target(DenoiseSlot::Output).Id)
                .StorageReadWrite(Target(DenoiseSlot::Variance).Id)
                .Execute(
                    [this, Bind, push](PassContext& inner)
                    {
                        const auto* view = static_cast<const SceneView*>(inner.UserData());
                        VE_ASSERT(view != nullptr, "SSR resolve pass: null SceneView");
                        const BindlessRegistry& registry = m_Context.GetBindlessRegistry();
                        CommandBuffer& cmd = inner.Cmd();
                        Bind(cmd, registry, m_Resolve);
                        SsrResolvePush framePush = push;
                        framePush.MaxAlpha = MaxAlphaOf(*view);
                        cmd.PushConstants(framePush);
                        cmd.DispatchIndirect(m_Arguments, DenoiseArgumentsOffset);
                    });
        }

        // History: what the next frame's reprojection compares against, over the whole extent, and
        // the output, variance and sample counts of every pixel that is not glossy cleared.
        {
            const uvec2 tiles = TileGrid(m_Extent);
            const SsrDenoiseHistoryPush push{
                .NormalTexture = normalHandle.Index,
                .AlphaTexture = m_AlphaHandle.Index,
                .DepthTexture = m_PyramidHandle.Index,
                .SampleCountTexture = Target(DenoiseSlot::SampleCount).Handle.Index,
                .Extent = m_Extent,
                .MaxAlpha = 0.0f,
                .Pad0 = 0,
            };
            graph.AddComputePass("SSR Denoise History")
                .Sample(normalId)
                .Sample(m_AlphaId)
                .Sample(depthLevel)
                .Sample(Target(DenoiseSlot::SampleCount).Id)
                .StorageWrite(Target(DenoiseSlot::NormalHistory).Id)
                .StorageWrite(Target(DenoiseSlot::AlphaHistory).Id)
                .StorageWrite(Target(DenoiseSlot::DepthHistory).Id)
                .StorageWrite(Target(DenoiseSlot::SampleCountHistory).Id)
                .StorageWrite(Target(DenoiseSlot::Output).Id)
                .StorageWrite(Target(DenoiseSlot::Variance).Id)
                .Execute(
                    [this, Bind, push, tiles](PassContext& inner)
                    {
                        const auto* view = static_cast<const SceneView*>(inner.UserData());
                        VE_ASSERT(view != nullptr, "SSR denoise history pass: null SceneView");
                        const BindlessRegistry& registry = m_Context.GetBindlessRegistry();
                        CommandBuffer& cmd = inner.Cmd();
                        Bind(cmd, registry, m_History);
                        SsrDenoiseHistoryPush framePush = push;
                        framePush.MaxAlpha = MaxAlphaOf(*view);
                        cmd.PushConstants(framePush);
                        cmd.Dispatch(tiles.x, tiles.y, 1);
                    });
        }
    }

    void SsrStochasticChain::SetCamera(const dvec3& cameraPosition,
                                       const dmat4& previousDirectionViewProj)
    {
        m_CameraPosition = cameraPosition;
        m_PrevClipTranslation = vec4(previousDirectionViewProj *
                                     glm::dvec4(cameraPosition - m_PreviousCameraPosition, 0.0));
    }

    void SsrStochasticChain::CommitHistory()
    {
        m_PreviousCameraPosition = m_CameraPosition;
        m_HistoryValid = IsAllocated();
    }

    void SsrStochasticChain::AppendBindings(std::vector<RenderGraph::ImportBinding>& bindings) const
    {
        if (!IsAllocated() || !m_RadianceId.IsValid())
        {
            return;
        }
        bindings.push_back({.Id = m_RayListId, .Buffer = m_RayList});
        bindings.push_back({.Id = m_TileListId, .Buffer = m_TileList});
        bindings.push_back({.Id = m_CountersId, .Buffer = m_Counters});
        bindings.push_back({.Id = m_ArgumentsId, .Buffer = m_Arguments});
        bindings.push_back({.Id = m_RadianceId, .View = m_RadianceView});
        bindings.push_back({.Id = m_AlphaId, .View = m_AlphaView});
        bindings.push_back({.Id = m_RayLengthId, .View = m_RayLengthView});
        for (u32 level = 0; level < m_PyramidMips.size(); level++)
        {
            bindings.push_back({.Id = m_PyramidChainId.Level(level), .View = m_PyramidMips[level]});
        }
        for (const DenoiseTarget& target : m_DenoiseTargets)
        {
            bindings.push_back({.Id = target.Id, .View = target.View});
        }
    }

    SsrTraceTargets SsrStochasticChain::GetTargets() const
    {
        return SsrTraceTargets{
            .RayList = m_RayList,
            .TileList = m_TileList,
            .Counters = m_Counters,
            .Arguments = m_Arguments,
            .Radiance = m_RadianceView,
            .Alpha = m_AlphaView,
            .BlueNoise = m_BlueNoiseView,
            .RayLength = m_RayLengthView,
            .Denoised = Target(DenoiseSlot::Output).View,
            .Variance = Target(DenoiseSlot::Variance).View,
        };
    }
